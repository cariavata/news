/**
 * Returns all published automated articles up to today (KST).
 * Strictly prevents leaking future articles (> today).
 * Supports from 2024-01-01 to 2040-12-31.
 */
export function getPublishedAutoArticles(limitCount = 180): Article[] {
  const todayStr = getTodayKSTString();
  const todayDate = new Date(todayStr + 'T00:00:00Z');
  const startDate = new Date('2024-01-01T00:00:00Z');

  const articles: Article[] = [];
  const currentDate = new Date(todayDate);

  let count = 0;
  while (currentDate >= startDate && count < limitCount) {
    const y = currentDate.getUTCFullYear();
    const m = String(currentDate.getUTCMonth() + 1).padStart(2, '0');
    const d = String(currentDate.getUTCDate()).padStart(2, '0');
    const dateStr = `${y}-${m}-${d}`;

    // Never publish future articles beyond today
    if (dateStr <= todayStr) {
      articles.push(generateArticleForDate(dateStr));
      count++;
    }

    currentDate.setUTCDate(currentDate.getUTCDate() - 1);
  }

  return articles;
}

/**
 * Get a specific automated article by ID if unlocked (<= today).
 */
export function getAutoArticleById(id: string): Article | null {
  if (!id.startsWith('auto-')) return null;
  const dateStr = id.replace('auto-', '');
  if (!/^\d{4}-\d{2}-\d{2}$/.test(dateStr)) return null;

  const todayStr = getTodayKSTString();
  if (dateStr > todayStr) {
    return null;
  }

  if (dateStr > '2040-12-31') {
    return null;
  }

  return generateArticleForDate(dateStr);
}
